(defn with-owner-db [f]
  (let [source (doto (JdbcDataSource.)
                 (.setURL (str "jdbc:h2:mem:nmcp_owners_" (UUID/randomUUID)))
                 (.setUser "sa") (.setPassword ""))
        anchor (.getConnection source)
        provider {:token-store (store/create-token-store)
                  :code-store (store/create-authorization-code-store)}]
    (try
      (with-open [statement (.createStatement ^Connection anchor)]
        (doseq [sql ddl] (.execute statement ^String sql)))
      (binding [app-db/*application-db* (app-db/application-db :h2 source)]
        (with-redefs-fn
          {#'access/inputs (constantly {:mode "two-accounts" :users "[23,47]"})
           #'pilot.config/inputs (constantly {:registry nil :path nil})
           #'system/site-url (constantly "https://analytics.example.invalid")
           #'oauth/get-provider (constantly provider)
           #'settings/unobfuscated-mcp-embedding-signing-secret (constantly "invented-native-mcp-signing-secret")
           #'session.model/session-hash-secret
           #(.getBytes "invented-native-session-hash-secret" StandardCharsets/UTF_8)
           ;; This fixture supplies role context only. Active-account admission and all store/session SQL remain real.
           #'request.session/with-current-user-fetch-user-for-id
           (fn [id] {:metabase-user-id id :is-superuser? false :settings {}})}
          #(f provider)))
      (finally
        (.close ^Connection anchor)
        (is (.isClosed ^Connection anchor))
        ;; No DB_CLOSE_DELAY or file URL. Reopening the name must create an empty database.
        (with-open [verify (.getConnection source)
                    tables (.getTables (.getMetaData ^Connection verify) nil "PUBLIC" "CORE_USER" nil)]
          (is (false? (.next tables))))))))

(defn snapshot []
  (into {} (map (fn [table] [table (set (t2/select table))]))
        [:core_user :core_session :mcp_query_handle :oauth_authorization_code :oauth_access_token :oauth_refresh_token]))

(defn save-tokens! [provider id]
  (let [access-token (str "invented-access-" id)
        refresh-token (str "invented-refresh-" id)
        expiry (+ (System/currentTimeMillis) 600000)
        token-store (:token-store provider)]
    (proto/save-access-token token-store (oidc.util/hash-token access-token) (str id)
                             "invented-native-client" scopes expiry [resource])
    (proto/save-refresh-token token-store (oidc.util/hash-token refresh-token) (str id)
                              "invented-native-client" scopes expiry [resource])
    {:access access-token :refresh refresh-token}))

(defn save-code! [provider id]
  (let [code (str "invented-code-" id)]
    (proto/save-authorization-code (:code-store provider) code (str id) "invented-native-client"
                                   "http://127.0.0.1:38171/callback" scopes nil
                                   (+ (System/currentTimeMillis) 600000) "invented-pkce-digest" "S256" [resource])
    code))

(defn denied-status [f]
  (try (f) nil (catch clojure.lang.ExceptionInfo e (:status-code (ex-data e)))))

(defn invoke [token sid method]
  (let [result (promise)
        request {:uri "/api/metabase-mcp" :request-method method
                 :headers {"authorization" (str "Bearer " token) "mcp-session-id" sid}
                 :body {:jsonrpc "2.0" :id 1 :method "ping" :params {}}}]
    (api/handler request #(deliver result %) #(deliver result %))
    (deref result 1000 ::timeout)))

(deftest actual-user-predicates-and-native-stores-admit-only-two-accounts-test
  (with-owner-db
    (fn [provider]
      (doseq [id [23 47]]
        (let [tokens (save-tokens! provider id)
              code (save-code! provider id)
              resolved (oauth/resolve-access-token (:access tokens))]
          (is (= id (:user-id resolved)))
          (is (= (set scopes) (:scopes resolved)))
          (is (= (str id) (:user-id (oidc.store/get-refresh-token (:token-store provider) (:refresh tokens)))))
          (is (= (str id) (:user-id (proto/get-authorization-code (:code-store provider) code))))))
      (let [before (snapshot)]
        (is (= 403 (denied-status #(save-tokens! provider 99))))
        (is (= 403 (denied-status #(save-code! provider 99))))
        (is (= before (snapshot)))))))

(deftest stored-historical-foreign-or-deactivated-grants-cannot-bypass-admission-test
  (with-owner-db
    (fn [provider]
      (let [own (save-tokens! provider 47)
            foreign (with-redefs [access/inputs (constantly {:mode nil :users nil})]
                      (save-tokens! provider 99))]
        (t2/update! :core_user 47 {:is_active false})
        (let [before (snapshot)]
          (doseq [tokens [own foreign]]
            (is (= 403 (denied-status #(oauth/resolve-access-token (:access tokens)))))
            (is (= 403 (denied-status #(oauth/validate-pilot-token-request!
                                        provider {:client_id "invented-native-client"
                                                  :grant_type "refresh_token" :refresh_token (:refresh tokens)})))))
          (is (= before (snapshot))))))))

(deftest native-authorization-code-consumption-rechecks-current-account-test
  (with-owner-db
    (fn [provider]
      (let [codes (:code-store provider)
            a (save-code! provider 23)
            b (save-code! provider 47)]
        (is (= "23" (:user-id (proto/consume-authorization-code codes a))))
        (is (nil? (proto/consume-authorization-code codes a)))
        (t2/update! :core_user 47 {:is_active false})
        (let [before (snapshot)]
          (is (= 403 (denied-status #(proto/consume-authorization-code codes b))))
          (is (= before (snapshot)))
          (is (= 1 (t2/count :oauth_authorization_code))))))))

(deftest native-access-and-refresh-revocation-is-exact-and-remains-available-test
  (with-owner-db
    (fn [provider]
      (let [tokens (:token-store provider) a (save-tokens! provider 23) b (save-tokens! provider 47)]
        (t2/update! :core_user 23 {:is_active false})
        (is (true? (proto/revoke-token tokens (oidc.util/hash-token (:access a)))))
        (is (nil? (oauth/resolve-access-token (:access a))))
        (is (some? (oidc.store/get-refresh-token tokens (:refresh a))))
        (is (true? (proto/revoke-token tokens (oidc.util/hash-token (:refresh a)))))
        (is (nil? (oidc.store/get-refresh-token tokens (:refresh a))))
        (is (= 47 (:user-id (oauth/resolve-access-token (:access b)))))
        (is (= "47" (:user-id (oidc.store/get-refresh-token tokens (:refresh b)))))))))

(deftest native-http-denies-cross-user-materialized-session-use-and-delete-test
  (with-owner-db
    (fn [provider]
      (let [a (save-tokens! provider 23) b (save-tokens! provider 47)
            sid (session/create! 23)
            handle (session/store-handle! sid 23 "invented-query")
            before (snapshot)]
        (is (= 200 (:status (invoke (:access a) sid :post))))
        (is (= 404 (:status (invoke (:access b) sid :post))))
        (is (= 404 (:status (invoke (:access b) sid :delete))))
        (is (= "invented-query" (session/read-handle sid 23 handle)))
        (is (= before (snapshot)))))))

(deftest native-handle-sql-is-user-scoped-with-intended-same-user-session-reuse-test
  (with-owner-db
    (fn [_]
      (let [a (session/create! 23) a2 (session/create! 23) b (session/create! 47)
            handle (session/store-handle! a 23 "invented-query" "invented-prompt")
            before (snapshot)]
        (is (= "invented-query" (session/read-handle a2 23 handle)))
        (is (= {:encoded_query "invented-query" :prompt "invented-prompt"}
               (session/resolve-query-handle a2 23 handle)))
        (is (nil? (session/read-handle b 47 handle)))
        (is (nil? (session/read-handle a 47 handle)))
        (doseq [bad [nil 1 true {:raw "invented"} [:raw "invented"] "not-a-handle"]]
          (is (nil? (session/read-handle b 47 bad))))
        (is (= before (snapshot)))))))

(deftest native-http-owned-session-cleanup-preserves-other-account-test
  (with-owner-db
    (fn [provider]
      (let [tokens (save-tokens! provider 23) a (session/create! 23) b (session/create! 47)
            h-a (session/store-handle! a 23 "invented-a")
            h-b (session/store-handle! b 47 "invented-b")
            before-b (t2/select-one :model/McpQueryHandle :id h-b)]
        (is (= 200 (:status (invoke (:access tokens) a :delete))))
        (is (false? (t2/exists? :model/McpQueryHandle :id h-a)))
        (is (= before-b (t2/select-one :model/McpQueryHandle :id h-b)))
        (is (= "invented-b" (session/read-handle b 47 h-b)))
        (is (= 1 (t2/count :core_session)))))))

